/** OKLCH (or rgb()) string -> [r, g, b, a] in 0..1 sRGB. */
function toSrgb(value) {
  const rgb = value.match(/^rgb\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*(?:\/\s*([\d.]+))?\s*\)$/);
  if (rgb) return [rgb[1] / 255, rgb[2] / 255, rgb[3] / 255, rgb[4] === undefined ? 1 : +rgb[4]];
  const m = value.match(/^oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*(?:\/\s*([\d.]+))?\s*\)$/);
  if (!m) throw new Error(`Unsupported colour: ${value}`);
  const [L, C, H] = [+m[1], +m[2], (+m[3] * Math.PI) / 180];
  const a = C * Math.cos(H);
  const b = C * Math.sin(H);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const mm = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const lin = [
    4.0767416621 * l - 3.3077115913 * mm + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * mm - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * mm + 1.707614701 * s,
  ];
  const gamma = (x) => (x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055);
  return [...lin.map((x) => Math.min(1, Math.max(0, gamma(x)))), m[4] === undefined ? 1 : +m[4]];
}

function dartColor(value) {
  const [r, g, b, a] = toSrgb(value);
  const hex = [a, r, g, b].map((x) => Math.round(x * 255).toString(16).padStart(2, '0')).join('');
  return `Color(0x${hex.toUpperCase()})`;
}

/** Adds an alpha to an oklch() string. */
const withAlpha = (oklch, alpha) => oklch.replace(/\)$/, ` / ${alpha})`);

/**
 * Derived spring values. duration/bounce use the SwiftUI model that Flutter's
 * SpringDescription.withDurationAndBounce reproduces: duration = 2*pi/omega,
 * bounce = 1 - zeta (under-damped) or 1/zeta - 1 (over-damped).
 */
function deriveSpring({ mass, stiffness, damping }) {
  const omega = Math.sqrt(stiffness / mass);
  const zeta = damping / (2 * Math.sqrt(stiffness * mass));
  const duration = (2 * Math.PI) / omega;
  const bounce = zeta < 1 ? 1 - zeta : 1 / zeta - 1;
  // Position of a spring released from 0 towards 1 at rest, at time t.
  const x = (t) => {
    if (zeta < 1) {
      const wd = omega * Math.sqrt(1 - zeta * zeta);
      return 1 - Math.exp(-zeta * omega * t) * (Math.cos(wd * t) + ((zeta * omega) / wd) * Math.sin(wd * t));
    }
    if (zeta === 1) return 1 - Math.exp(-omega * t) * (1 + omega * t);
    const r1 = -omega * (zeta - Math.sqrt(zeta * zeta - 1));
    const r2 = -omega * (zeta + Math.sqrt(zeta * zeta - 1));
    return 1 - (r2 * Math.exp(r1 * t) - r1 * Math.exp(r2 * t)) / (r2 - r1);
  };
  // Settle when it stays within 0.1% of the target.
  let settle = 0;
  for (let t = 0; t < 5; t += 0.001) if (Math.abs(1 - x(t)) > 0.001) settle = t;
  settle = Math.ceil(settle * 1000) / 1000;
  const steps = 40;
  const stops = Array.from({ length: steps + 1 }, (_, i) => +x((settle * i) / steps).toFixed(4));
  stops[steps] = 1;
  return {
    mass, stiffness, damping,
    dampingRatio: +zeta.toFixed(4),
    duration: +duration.toFixed(4),
    bounce: +bounce.toFixed(4),
    settleMs: Math.round(settle * 1000),
    cssEasing: `linear(${stops.join(', ')})`,
  };
}

const px = (v) => parseFloat(v);
const ms = (v) => parseFloat(v);
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
