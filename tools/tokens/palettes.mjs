#!/usr/bin/env node
// Writes a spec card for every palette: tokens/brand/PALETTES.md plus one swatch SVG each.
//
//   node tools/tokens/palettes.mjs
//
// Each card shows the palette's mood and best uses (the brand file's "spec"), its key
// colours in light and dark, and the contrast receipt: the weakest pair for each rule in
// every mode, measured by the same build that fails a brand on contrast.

import { execFileSync } from 'node:child_process';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { toSrgb } from './color.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const tmp = join(root, 'node_modules/.cache/aurum-palettes');
const swatchDir = join(root, 'tokens/brand/swatches');
await mkdir(tmp, { recursive: true });
await mkdir(swatchDir, { recursive: true });

const hex = (v) => `#${toSrgb(v).slice(0, 3).map((x) => Math.round(x * 255).toString(16).padStart(2, '0')).join('').toUpperCase()}`;
const MODE_NAMES = { light: 'Light', dark: 'Dark', contrastLight: 'Light, more contrast', contrastDark: 'Dark, more contrast' };
const short = (t) => t.replace(/^color-/, '');

const files = [
  { file: join(root, 'tokens/brand/aurum.json'), slug: 'aurum', rel: 'aurum.json' },
  ...(await readdir(join(root, 'tokens/brand/examples')))
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => ({ file: join(root, 'tokens/brand/examples', f), slug: f.replace(/\.json$/, ''), rel: `examples/${f}` })),
];

function swatch(r) {
  const row = (mode, y) => {
    const c = Object.fromEntries(Object.entries(r.modes[mode].colors).map(([k, v]) => [short(k), hex(v)]));
    return `  <g transform="translate(0 ${y})">
    <rect width="360" height="88" rx="20" fill="${c['surface-canvas']}"/>
    <rect x="12" y="12" width="200" height="64" rx="14" fill="${c['surface-card']}"/>
    <text x="28" y="42" font-family="Georgia, serif" font-size="20" fill="${c['text-primary']}">${r.name}</text>
    <text x="28" y="62" font-family="system-ui, sans-serif" font-size="12" fill="${c['text-secondary']}">${MODE_NAMES[mode]}</text>
    <rect x="226" y="26" width="84" height="36" rx="18" fill="${c.accent}"/>
    <text x="268" y="49" text-anchor="middle" font-family="system-ui, sans-serif" font-size="13" font-weight="600" fill="${c['on-accent']}">Button</text>
    <circle cx="334" cy="44" r="10" fill="${c['accent-secondary']}"/>
  </g>`;
  };
  return `<svg xmlns="http://www.w3.org/2000/svg" width="360" height="184" viewBox="0 0 360 184" role="img" aria-label="${r.name} palette in light and dark">
${row('light', 0)}
${row('dark', 96)}
</svg>
`;
}

const cards = [];
for (const { file, slug, rel } of files) {
  const raw = JSON.parse(await readFile(file, 'utf8'));
  const out = join(tmp, `${slug}.json`);
  execFileSync('node', [join(root, 'tools/tokens/build.mjs'), '--brand', file, '--report', out], { stdio: 'pipe' });
  const r = JSON.parse(await readFile(out, 'utf8'));
  await writeFile(join(swatchDir, `${slug}.svg`), swatch(r));

  const spec = raw.spec ?? {};
  const key = (mode) =>
    ['accent', 'accent-secondary', 'surface-canvas', 'text-primary']
      .map((k) => `${k} \`${hex(r.modes[mode].colors[`color-${k}`])}\``)
      .join(' · ');
  const checks = Object.keys(MODE_NAMES).map((mode) => {
    const cells = r.modes[mode].checks.map((c) => `${c.pass ? '✓' : '✗'} ${c.ratio}`);
    return `| ${MODE_NAMES[mode]} | ${cells.join(' | ')} |`;
  });
  const ruleHead = r.modes.light.checks.map((c) => `${c.why} (≥ ${c.min})`).join(' | ');
  cards.push(`## ${r.name}${slug === 'aurum' ? ' (default)' : ''}

![${r.name} palette](swatches/${slug}.svg)

${spec.mood ?? '_No spec yet. Add a "spec" to the brand file._'}

${spec.bestFor?.length ? `- **Best for:** ${spec.bestFor.join(', ')}\n` : ''}${spec.avoid ? `- **Avoid for:** ${spec.avoid}\n` : ''}- **Light:** ${key('light')}
- **Dark:** ${key('dark')}
- **File:** [\`${rel}\`](${rel})

Contrast receipt: the weakest pair for each rule (WCAG 2.2 AA).

| Mode | ${ruleHead} |
| --- | ${r.modes.light.checks.map(() => ':-:').join(' | ')} |
${checks.join('\n')}`);
}

const md = `<!-- Generated by tools/tokens/palettes.mjs from the brand files. Do not edit by hand: run \`pnpm palettes\`. -->

# Aurum palettes

Every palette is one brand file. Pick one for an app, or copy one as a starting point. Each card shows what it's for and proves it's readable: the build refuses any palette that fails a contrast rule, and the receipt lists its weakest pair per rule, in all four modes.

${cards.join('\n\n')}
`;
await writeFile(join(root, 'tokens/brand/PALETTES.md'), md);
console.log(`Wrote tokens/brand/PALETTES.md and ${files.length} swatches.`);
