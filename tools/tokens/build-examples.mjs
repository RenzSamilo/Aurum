// Builds every example brand in tokens/brand/examples/ into the Flutter
// example app, so its palette switcher can show them side by side.
//
//   node tools/tokens/build-examples.mjs
//
// Each build runs the same contrast checks as an app build and fails the same way.

import { execFileSync } from 'node:child_process';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const examples = join(root, 'tokens/brand/examples');
const out = join(root, 'packages/flutter/example/lib/brands');
const tmp = join(root, 'node_modules/.cache/aurum-brands');

const files = (await readdir(examples)).filter((f) => f.endsWith('.json')).sort();
const entries = [];
for (const file of files) {
  const slug = file.replace(/\.json$/, '');
  const { name } = JSON.parse(await readFile(join(examples, file), 'utf8'));
  execFileSync(
    'node',
    [join(root, 'tools/tokens/build.mjs'), '--brand', join(examples, file), '--css', join(tmp, `${slug}.css`), '--dart', join(out, `${slug}.g.dart`)],
    { stdio: 'inherit' },
  );
  const ident = name.toLowerCase().replace(/\s+(\w)/g, (_, c) => c.toUpperCase()) + 'Brand';
  entries.push({ slug, ident });
}

await writeFile(
  join(out, 'brands.g.dart'),
  `// GENERATED by tools/tokens/build-examples.mjs. Do not edit.

import 'package:aurum_ui/aurum_ui.dart';

${entries.map((e) => `import '${e.slug}.g.dart';`).join('\n')}

/// The default brand first, then every example brand by name.
const List<AurumBrand> exampleBrands = [
  aurumBrand,
${entries.map((e) => `  ${e.ident},`).join('\n')}
];
`,
);
console.log(`Built ${entries.length} example brands into packages/flutter/example/lib/brands/.`);
