#!/usr/bin/env node
// Builds Aurum's design tokens for every platform from one source.
//
//   tokens/brand/<name>.json        the brand: hues, tint, fonts, corner scale
//   tokens/primitive/*.json         raw values that do not change per brand
//   tokens/semantic/<mode>.json     meaning per colour mode
//
// Core build (no flags) writes, for the default brand:
//   packages/react/src/tokens/tokens.css                 CSS custom properties + modes
//   packages/react/src/tokens/tokens.ts                  typed JS values
//   packages/flutter/lib/src/tokens/aurum_tokens.g.dart  Dart constants + AurumColors
//   packages/flutter/lib/src/tokens/aurum_brand.g.dart   the default AurumBrand
//
// App build, for an app's own brand:
//   node tools/tokens/build.mjs --brand my.brand.json --css src/aurum-tokens.css --dart lib/my_brand.g.dart
//
// Every build fails if the brand breaks a contrast rule in any mode.

import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import StyleDictionary from 'style-dictionary';

import { brandTokens, loadBrand } from './brand.mjs';
import { dartColor, withAlpha } from './color.mjs';
import { deriveSpring } from './spring.mjs';
import { contrastReport, validateContrast } from './validate.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const { values: args } = parseArgs({
  options: {
    brand: { type: 'string' },
    css: { type: 'string' },
    dart: { type: 'string' },
    // Writes a JSON receipt: key colours and the worst contrast pair per rule, per mode.
    report: { type: 'string' },
  },
});
const appBuild = Boolean(args.brand);
if (appBuild && !args.css && !args.dart && !args.report) throw new Error('--brand needs --css, --dart and/or --report to say where to write.');

const brandPath = resolve(args.brand ?? join(root, 'tokens/brand/aurum.json'));
const brand = await loadBrand(brandPath);
const HEADER = `GENERATED by tools/tokens/build.mjs for the "${brand.name}" brand. Do not edit by hand.`;

const MODES = {
  light: ['semantic/light.json'],
  dark: ['semantic/dark.json'],
  contrastLight: ['semantic/light.json', 'semantic/contrast-light.json'],
  contrastDark: ['semantic/dark.json', 'semantic/contrast-dark.json'],
};

// ---------------------------------------------------------------------------
// Load

const scratch = await mkdtemp(join(tmpdir(), 'aurum-tokens-'));
const brandFile = join(scratch, 'brand.tokens.json');
await writeFile(brandFile, JSON.stringify(brandTokens(brand)));

async function load(files) {
  const sd = new StyleDictionary({
    source: [brandFile, join(root, 'tokens/primitive/**/*.json'), ...files.map((f) => join(root, 'tokens', f))],
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms: { aurum: { transforms: ['name/kebab'] } },
  });
  await sd.hasInitialized;
  const { allTokens } = await sd.getPlatformTokens('aurum');
  return new Map(allTokens.map((t) => [t.name, t]));
}

const modes = {};
for (const [mode, files] of Object.entries(MODES)) modes[mode] = await load(files);
await rm(scratch, { recursive: true, force: true });
const base = modes.light;

const isSemantic = (t) => t.filePath.includes('/semantic/');
const pick = (prefix) => [...base.values()].filter((t) => t.path[0] === prefix);
const semanticNames = [...base.values()].filter(isSemantic).map((t) => t.name);

// ---------------------------------------------------------------------------
// Collect

const px = (v) => parseFloat(v);
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascal = (s) => camel(s).replace(/^./, (c) => c.toUpperCase());
const dims = (prefix) => Object.fromEntries(pick(prefix).map((t) => [t.path.slice(1).join('-'), t.$value]));

const springs = Object.fromEntries(pick('spring').map((t) => [t.path[1], deriveSpring(t.$value)]));
/** Core text roles, the same for every brand (Dart AurumType). */
const coreTypes = Object.fromEntries(pick('type').map((t) => [t.path[1], { ...t.$value }]));
/** Text roles as this brand renders them (CSS and TS): display overrides applied. */
const types = structuredClone(coreTypes);
const haptics = Object.fromEntries(pick('haptic').map((t) => [t.path[1], t.$value]));
const durations = Object.fromEntries(pick('duration').map((t) => [t.path[1], px(t.$value)]));
const space = dims('space');
const radius = dims('radius');
const size = dims('size');
const z = dims('z');
const press = dims('press');
const gesture = dims('gesture');
const material = pick('material');
const materialBlur = Object.fromEntries(material.filter((t) => t.path[1] === 'blur').map((t) => [t.path[2], t.$value]));
const materialSat = Object.fromEntries(material.filter((t) => t.path[1] === 'saturation').map((t) => [t.path[2], t.$value]));
const shadows = Object.fromEntries(pick('shadow').map((t) => [t.path[1], t.$value]));
const ease = base.get('ease-standard').$value;
const smoothing = base.get('shape-smoothing').$value;
const fontUi = base.get('font-family-ui').$value;
const fontMono = base.get('font-family-mono').$value;
const fontDisplay = base.get('font-family-display').$value;
/** Title roles that use the display font. */
const DISPLAY_ROLES = new Set(['display', 'page', 'section', 'card']);
const bundled = { Inter: 'aurum_ui', Fraunces: 'aurum_ui' };
// A display font gets its own weight and tracking; serifs rarely suit the UI font's.
// Flutter applies the same overrides through AurumTypeface at runtime.
const displayWeight = fontDisplay !== fontUi ? (brand.font.displayWeight ?? null) : null;
const displayTracking = fontDisplay !== fontUi ? (brand.font.displayTracking ?? null) : null;
if (fontDisplay !== fontUi) {
  for (const k of DISPLAY_ROLES) {
    if (brand.font.displayWeight != null) types[k].weight = brand.font.displayWeight;
    if (brand.font.displayTracking != null) types[k].tracking = brand.font.displayTracking;
  }
}
const levels = Object.keys(materialBlur);

/** Semantic values of one mode, plus composed material tints. */
function semantic(mode) {
  const map = modes[mode];
  const vals = Object.fromEntries(semanticNames.map((n) => [n, map.get(n).$value]));
  for (const l of levels) vals[`material-tint-${l}`] = withAlpha(vals['material-tint-base'], vals[`material-alpha-${l}`]);
  return vals;
}
const sem = Object.fromEntries(Object.keys(MODES).map((m) => [m, semantic(m)]));
const diff = (a, b) => Object.fromEntries(Object.entries(sem[b]).filter(([k, v]) => sem[a][k] !== v));

const failures = validateContrast(sem);
if (failures.length) {
  console.error(`Brand "${brand.name}" fails contrast in ${failures.length} place(s):\n${failures.map((f) => `  ${f}`).join('\n')}`);
  console.error('Fix: darken the light accent (lower accent.lightnessLight), lighten the dark one (raise lightnessDark), or lower accent.chroma.');
  process.exit(1);
}

// ---------------------------------------------------------------------------
// CSS

const shadowCss = (s) => `${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${s.color}`;
const rem = (n) => `${+(n / 16).toFixed(4)}rem`;
const decl = (obj, indent = '  ') =>
  Object.entries(obj)
    .map(([k, v]) => (k === 'color-scheme' ? `${indent}color-scheme: ${v};` : `${indent}--${k}: ${v};`))
    .join('\n');
const block = (sel, obj) => `${sel} {\n${decl(obj)}\n}`;
const media = (q, sel, obj) => `@media ${q} {\n  ${sel} {\n${decl(obj, '    ')}\n  }\n}`;
const fontStack = fontUi === 'Inter' ? `"Inter Variable", "Inter", system-ui, sans-serif` : `"${fontUi}", system-ui, sans-serif`;
const displayStack =
  fontDisplay === fontUi ? 'var(--font-family-ui)'
  : fontDisplay === 'Fraunces' ? `"Fraunces Variable", "Fraunces", Georgia, serif`
  : `"${fontDisplay}", var(--font-family-ui)`;

const cssBase = {
  'color-scheme': 'light',
  ...Object.fromEntries(Object.entries(space).map(([k, v]) => [`space-${k}`, v])),
  ...Object.fromEntries(Object.entries(radius).map(([k, v]) => [`radius-${k}`, v])),
  'shape-smoothing': smoothing,
  // Native corner-shape that matches the smoothed path (see squircle.ts): stretch the
  // radius by (1 + smoothing), then pick the superellipse that meets the circular arc's
  // midpoint on the diagonal. CSS superellipse(K) has exponent 2^K.
  'shape-radius-scale': 1 + smoothing,
  'shape-superellipse': +Math.log2(-1 / Math.log2(1 - (1 - Math.SQRT1_2) / (1 + smoothing))).toFixed(3),
  ...Object.fromEntries(Object.entries(size).map(([k, v]) => [`size-${k}`, v])),
  ...Object.fromEntries(Object.entries(z).map(([k, v]) => [`z-${k}`, v])),
  'font-family-ui': fontStack,
  'font-family-mono': `"${fontMono}", ui-monospace, monospace`,
  'font-family-display': displayStack,
  ...Object.fromEntries(
    Object.entries(types).flatMap(([k, t]) => [
      [`type-${k}-size`, rem(t.size)],
      [`type-${k}-line-height`, rem(t.lineHeight)],
      [`type-${k}-weight`, t.weight],
      [`type-${k}-tracking`, `${t.tracking}em`],
    ]),
  ),
  ...Object.fromEntries(Object.entries(durations).map(([k, v]) => [`duration-${k}`, `${v}ms`])),
  'ease-standard': `cubic-bezier(${ease.join(', ')})`,
  ...Object.fromEntries(
    Object.entries(springs).flatMap(([k, s]) => [
      [`spring-${k}-easing`, s.cssEasing],
      [`spring-${k}-duration`, `${s.settleMs}ms`],
    ]),
  ),
  ...Object.fromEntries(Object.entries(press).map(([k, v]) => [`press-${k}`, v])),
  ...Object.fromEntries(Object.entries(materialBlur).map(([k, v]) => [`material-blur-${k}`, v])),
  ...Object.fromEntries(Object.entries(materialSat).map(([k, v]) => [`material-saturation-${k}`, v])),
  ...Object.fromEntries(Object.entries(shadows).map(([k, v]) => [`shadow-${k}`, shadowCss(v)])),
};

const reducedTransparency = {
  ...Object.fromEntries(levels.map((l) => [`material-blur-${l}`, '0px'])),
  ...Object.fromEntries(levels.map((l) => [`material-tint-${l}`, 'var(--color-surface-elevated)'])),
};
const reducedMotion = Object.fromEntries(Object.keys(press).map((k) => [`press-${k}`, 1]));
const dark = { 'color-scheme': 'dark', ...diff('light', 'dark') };

const typeClasses = Object.keys(types)
  .map(
    (k) => `.aurum-type-${k} {
  font-family: var(--font-family-${DISPLAY_ROLES.has(k) ? 'display' : 'ui'});
  font-size: var(--type-${k}-size);
  line-height: var(--type-${k}-line-height);
  font-weight: var(--type-${k}-weight);
  letter-spacing: var(--type-${k}-tracking);
}`,
  )
  .join('\n');

// Order matters: later rules with equal specificity win.
const css = `/* ${HEADER} */

/* Modes: data-theme="light|dark", data-contrast="more|normal", data-transparency="reduced|normal",
   data-motion="reduced|normal" on <html>. Without attributes, the system preference applies. */

${block(':root', { ...cssBase, ...sem.light })}

${media('(prefers-color-scheme: dark)', ':root:not([data-theme="light"])', dark)}

${block(':root[data-theme="dark"]', dark)}

${media('(prefers-contrast: more)', ':root:not([data-contrast="normal"])', diff('light', 'contrastLight'))}

${block(':root[data-contrast="more"]', diff('light', 'contrastLight'))}

${media('(prefers-contrast: more) and (prefers-color-scheme: dark)', ':root:not([data-contrast="normal"]):not([data-theme="light"])', diff('dark', 'contrastDark'))}

${media('(prefers-contrast: more)', ':root[data-theme="dark"]:not([data-contrast="normal"])', diff('dark', 'contrastDark'))}

${media('(prefers-color-scheme: dark)', ':root[data-contrast="more"]:not([data-theme="light"])', diff('dark', 'contrastDark'))}

${block(':root[data-contrast="more"][data-theme="dark"]', diff('dark', 'contrastDark'))}

/* Safari and Firefox ignore this query, so the in-app setting (data-transparency) is required. */
${media('(prefers-reduced-transparency: reduce)', ':root:not([data-transparency="normal"])', reducedTransparency)}

${block(':root[data-transparency="reduced"]', reducedTransparency)}

${media('(prefers-reduced-motion: reduce)', ':root:not([data-motion="normal"])', reducedMotion)}

${block(':root[data-motion="reduced"]', reducedMotion)}

${typeClasses}
`;

